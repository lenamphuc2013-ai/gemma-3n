import gradio as gr
import traceback
from llama_cpp import Llama

# Hàm kiểm tra và xử lý lỗi đồng thời đồng bộ cấu trúc Chat cho Gemma 3
def predict_stream(message, history):
    try:
        # 1. Kiểm tra xem biến mô hình 'llm' đã tồn tại trong Colab chưa
        if 'llm' not in globals():
            yield "❌ Lỗi: Biến mô hình 'llm' chưa được khởi tạo. Bạn hãy chạy ô code nạp mô hình Gemma 3n ở phía trên trước nhé!"
            return

        # 2. Xây dựng cấu trúc hội thoại chuẩn hóa
        messages = []

        # Duyệt qua lịch sử chat của Gradio để chuyển sang cấu trúc OpenAI/Llama-cpp
        for h in history:
            # Gradio phiên bản mới trả về dict hoặc đối tượng có thuộc tính, phiên bản cũ trả về list/tuple
            if isinstance(h, dict):
                user_content = h.get("text", "") or h.get("content", "")
                ai_content = h.get("text", "") or h.get("content", "")
                messages.append({"role": "user", "content": str(user_content)})
                messages.append({"role": "assistant", "content": str(ai_content)})
            elif isinstance(h, (list, tuple)) and len(h) == 2:
                messages.append({"role": "user", "content": str(h[0])})
                messages.append({"role": "assistant", "content": str(h[1])})

        # Thêm tin nhắn hiện tại của người dùng
        messages.append({"role": "user", "content": str(message)})

        # 3. Gọi mô hình xử lý dạng luồng (Streaming)
        response = llm.create_chat_completion(
            messages=messages,
            stream=True,
            temperature=0.7,
            top_p=0.9,
            max_tokens=1024
        )

        partial_message = ""
        for chunk in response:
            if "choices" in chunk and len(chunk["choices"]) > 0:
                delta = chunk["choices"][0].get("delta", {})
                if "content" in delta and delta["content"]:
                    partial_message += delta["content"]
                    yield partial_message

    except Exception as e:
        # Nếu có lỗi phát sinh nội bộ, in chi tiết lỗi ra màn hình Colab để kiểm tra
        error_msg = f"❌ Đã xảy ra lỗi hệ thống: {str(e)}"
        print(f"\n--- CHI TIẾT LỖI LOGS ---")
        traceback.print_exc()
        yield error_msg

# Tạo giao diện Web portal với khung Blocks an toàn
with gr.Blocks(theme="soft") as demo:
    gr.ChatInterface(
        fn=predict_stream,
        title="🤖 Cổng API và trò chuyện địa phương Gemma 3n",
        description="Nội bộ mô hình kết nối giao diện Gemma 3n, hỗ trợ hiển thị dạng luồng dữ liệu (Truyền phát) và API cổng.",
        textbox=gr.Textbox(placeholder="Nhập tin nhắn vào đây...", container=False, scale=7),
    )

# Chạy server ứng dụng và cấp link public
demo.queue().launch(share=True, debug=True)